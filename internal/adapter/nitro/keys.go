// i32Wrap 32 位有符号环绕。
func i32Wrap(v int64) int64 {
	v &= 0xffffffff
	if v >= 0x80000000 {
		v -= 0x100000000
	}
	return v
}

// entryKey 派生单条目内容密钥（低 8 位）。
//
// Garbro/nipa 公式：key = ((nameKey - Σname) * len + arcKey) * unpacked。
// name 既可能是解密后的明文名（鬼哭街重制版实测）也可能是加密名（Garbro
// RawName），由调用方两种都试。
func entryKey(name []byte, unpacked int64, arcKey int64) byte {
	sum := int64(nameKey)
	for _, b := range name {
		sum -= int64(b)
	}
	k := i32Wrap(i32Wrap(sum) * int64(len(name)))
	k = i32Wrap(k + arcKey)
	k = i32Wrap(k * unpacked)
	return byte(k & 0xff)
}
